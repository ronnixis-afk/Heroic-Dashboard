/**
 * Regenerates src/constants/originItemCatalog.ts from the RPG source of truth.
 *
 * Source: ../Heroic AI RPG/heroic-ai-rpg/src/config/startingStories.ts
 * Override with HEROIC_RPG_ROOT if the repos are not siblings.
 *
 * Usage: npm run sync:origin-item-catalog
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dashboardRoot = path.resolve(__dirname, '..');

const defaultRpgRoot = path.resolve(dashboardRoot, '..', 'Heroic AI RPG', 'heroic-ai-rpg');
const rpgRoot = process.env.HEROIC_RPG_ROOT
  ? path.resolve(process.env.HEROIC_RPG_ROOT)
  : defaultRpgRoot;

const sourcePath = path.join(rpgRoot, 'src', 'config', 'startingStories.ts');
const outPath = path.join(dashboardRoot, 'src', 'constants', 'originItemCatalog.ts');

const failSoft = process.argv.includes('--optional');

if (!fs.existsSync(sourcePath)) {
  const message = `Starting stories source not found at:\n  ${sourcePath}\nSet HEROIC_RPG_ROOT or place the RPG repo as a sibling of Heroic-Dashboard.`;
  if (failSoft) {
    console.warn(`[sync:origin-item-catalog] Skipped — ${message}`);
    process.exit(0);
  }
  console.error(`[sync:origin-item-catalog] ${message}`);
  process.exit(1);
}

const src = fs.readFileSync(sourcePath, 'utf8');

const start = src.indexOf('export const STARTING_STORIES');
if (start < 0) {
  console.error('[sync:origin-item-catalog] Could not find export const STARTING_STORIES in source.');
  process.exit(1);
}

const eq = src.indexOf('=', start);
const arrStart = src.indexOf('{', eq);
let depth = 0;
let end = -1;
for (let i = arrStart; i < src.length; i++) {
  if (src[i] === '{') depth++;
  else if (src[i] === '}') {
    depth--;
    if (depth === 0) {
      end = i;
      break;
    }
  }
}

if (end < 0) {
  console.error('[sync:origin-item-catalog] Could not parse STARTING_STORIES object bounds.');
  process.exit(1);
}

const body = src.slice(arrStart, end + 1);

// We need to parse each top-level key in STARTING_STORIES
const knownOriginIds = [
  'humble_beginnings',
  'the_drifter',
  'the_blank_slate',
  'the_pariah',
  'the_fallen_house',
];

const entries = [];

for (const originId of knownOriginIds) {
  const originIdx = body.indexOf(`${originId}:`);
  if (originIdx < 0) continue;

  const braceStart = body.indexOf('{', originIdx);
  if (braceStart < 0) continue;

  let d = 0;
  let blockEnd = -1;
  for (let j = braceStart; j < body.length; j++) {
    if (body[j] === '{') d++;
    else if (body[j] === '}') {
      d--;
      if (d === 0) {
        blockEnd = j;
        break;
      }
    }
  }

  if (blockEnd < 0) continue;
  const block = body.slice(braceStart, blockEnd + 1);

  const titleMatch = block.match(/title:\s*['"]([^'"]+)['"]/);
  const keepsakeIdx = block.indexOf('keepsake:');
  let keepsakeName = '';
  let keepsakeDesc = '';
  let keepsakeTemplate = '';

  if (keepsakeIdx >= 0) {
    const keepsakeBlock = block.slice(keepsakeIdx);
    const nameMatch = keepsakeBlock.match(/name:\s*(?:'((?:\\'|[^'])*)'|"((?:\\"|[^"])*)")/);
    const descMatch = keepsakeBlock.match(/description:\s*(?:'((?:\\'|[^'])*)'|"((?:\\"|[^"])*)")/);
    const templateMatch = keepsakeBlock.match(/templateName:\s*(?:'((?:\\'|[^'])*)'|"((?:\\"|[^"])*)")/);

    if (nameMatch) keepsakeName = (nameMatch[1] ?? nameMatch[2] ?? '').replace(/\\'/g, "'").replace(/\\"/g, '"');
    if (descMatch) keepsakeDesc = (descMatch[1] ?? descMatch[2] ?? '').replace(/\\'/g, "'").replace(/\\"/g, '"');
    if (templateMatch) keepsakeTemplate = (templateMatch[1] ?? templateMatch[2] ?? '').replace(/\\'/g, "'").replace(/\\"/g, '"');
  }

  if (titleMatch && keepsakeName) {
    entries.push({
      id: originId,
      name: keepsakeName,
      storyTitle: titleMatch[1],
      description: keepsakeDesc,
      itemType: keepsakeTemplate,
    });
  }
}

if (entries.length === 0) {
  console.error('[sync:origin-item-catalog] Parsed zero origin item entries.');
  process.exit(1);
}

const generatedAt = new Date().toISOString().slice(0, 10);

const serializeEntries = entries
  .map(
    (e) => `  {
    id: '${e.id}',
    name: ${JSON.stringify(e.name)},
    storyTitle: ${JSON.stringify(e.storyTitle)},
    description: ${JSON.stringify(e.description)},
    itemType: ${JSON.stringify(e.itemType)},
  }`
  )
  .join(',\n');

const fileContent = `/**
 * AUTO-GENERATED by scripts/extract-origin-item-catalog.mjs — do not edit by hand.
 *
 * Origin Item catalog for Media Library uploads.
 * Source of truth: heroic-ai-rpg/src/config/startingStories.ts
 *
 * Regenerate:
 *   npm run sync:origin-item-catalog
 *
 * Last synced: ${generatedAt}
 *
 * One picture per origin keepsake. The live game looks up keepsake art with:
 *   GET /api/image-assets/origin-item-defaults?startingStoryId=<id>
 * expecting assetType "Origin Item", genre "Any Genre", and
 * metadata.startingStoryId equal to one of these ids.
 */

export interface OriginItemOption {
  id: string;
  name: string;
  storyTitle: string;
  description: string;
  itemType: string;
}

export const ORIGIN_ITEM_OPTIONS: readonly OriginItemOption[] = [
${serializeEntries}
] as const;

export type OriginItemStartingStoryId = (typeof ORIGIN_ITEM_OPTIONS)[number]['id'];

const ORIGIN_ITEM_IDS = new Set<string>(ORIGIN_ITEM_OPTIONS.map((option) => option.id));

export const isOriginItemStartingStoryId = (value: string): value is OriginItemStartingStoryId =>
  ORIGIN_ITEM_IDS.has(value);

export const getOriginItemOption = (startingStoryId: string): OriginItemOption | undefined =>
  ORIGIN_ITEM_OPTIONS.find((option) => option.id === startingStoryId);

export const getOriginItemDisplayName = (startingStoryId: string): string =>
  ORIGIN_ITEM_OPTIONS.find((option) => option.id === startingStoryId)?.name || startingStoryId;

export const getOriginItemStoryTitle = (startingStoryId: string): string =>
  ORIGIN_ITEM_OPTIONS.find((option) => option.id === startingStoryId)?.storyTitle || startingStoryId;

export const getOriginItemDescription = (startingStoryId: string): string =>
  ORIGIN_ITEM_OPTIONS.find((option) => option.id === startingStoryId)?.description || '';

export const getOriginItemType = (startingStoryId: string): string =>
  ORIGIN_ITEM_OPTIONS.find((option) => option.id === startingStoryId)?.itemType || '';
`;

fs.writeFileSync(outPath, fileContent);
console.log(
  `[sync:origin-item-catalog] Wrote ${entries.length} entries to ${path.relative(dashboardRoot, outPath)}`
);
